#!/usr/bin/env python3
"""Sends the store listing, a release or nothing but a check to Google Play.

    python3 tool/play_publish.py listing                  # check only, changes nothing
    python3 tool/play_publish.py listing --commit         # texts and images go live
    python3 tool/play_publish.py release app-release.aab  # check only
    python3 tool/play_publish.py release app-release.aab --commit
    python3 tool/play_publish.py reviews                  # the last week's reviews
    python3 tool/play_publish.py selftest                 # no network, no key

Run by .github/workflows/play-store.yaml; the steps the owner takes once are
in ANLEITUNG.md. It talks to the Google Play Developer API (androidpublisher
v3) through Google's own client library, and every call below was checked
against the API's discovery document, revision 20261026, which that library
ships — `selftest` replays the calls against it without touching the network.

What it does, and what it deliberately does not:

* **Without --commit nothing changes.** The edit is validated by Google and
  thrown away. That is the default on purpose: the account has been suspended
  once, and a second incident ends the project (HANDOVER.md).
* **Four listings** — en-US, de-DE, es-419, pt-BR — from the layout
  tool/export_play_metadata.py writes (--with-copies adds es-ES with the
  Spanish text). Every other store language is the Play Console's own
  translation and is never touched: nothing is deleted, no language is
  created that the export does not contain.
* Texts are *patched*, not replaced: a listing's promo-video link stays as it
  is in the Console. A language the store does not have yet is created.
* Images of a kind are replaced together (all phone screenshots, the feature
  graphic). The icon is never uploaded from here.
* `--clear-other-images` is the one exception to "never touched": it removes
  the phone screenshots and the feature graphic of every *other* language, so
  that those show the default language's pictures instead of the ones typed
  in by hand in September. Their texts stay. Off unless asked for.
* A release is uploaded as a **draft** unless told otherwise: it appears in
  the Console ready to roll out, and a person presses the button.
* `--ai-state` passes Google's "was this image generated by AI" attestation
  with each image. It is left unset by default: that statement is the
  account holder's to make, not a script's.
* `reviews` prints rating, text, language, app version and date. Never the
  reviewer's name: the output lands in a build log.

The key: a service-account JSON, as a file named by PLAY_SERVICE_ACCOUNT_JSON
or by GOOGLE_APPLICATION_CREDENTIALS. Never commit it — .gitignore keeps
*service-account*.json out, and the repository is public.
"""

from __future__ import annotations

import argparse
import glob
import json
import os
import re
import sys

PACKAGE = "com.thinkube.qubble"
SCOPE = "https://www.googleapis.com/auth/androidpublisher"
METADATA = "build/play-metadata/android"
# Play's limits for the fields sent here (docs/STORE-LISTING.md,
# test/release_notes_test.dart).
LIMITS = {"title": 30, "short_description": 80, "full_description": 4000}
NOTES_LIMIT = 500
AI_STATES = {
    "not-ai": "aiGeneratedStateNotAiGenerated",
    "ai": "aiGeneratedStateAiGeneratedDeveloperAttested",
}
STATUSES = ("draft", "inProgress", "completed")


def log(text: str = "") -> None:
    print(text, flush=True)


def credentials_path() -> str:
    for name in ("PLAY_SERVICE_ACCOUNT_JSON", "GOOGLE_APPLICATION_CREDENTIALS"):
        path = os.environ.get(name)
        if path:
            if not os.path.exists(path):
                sys.exit(f"{name} names {path}, which does not exist")
            return path
    sys.exit("no key: set PLAY_SERVICE_ACCOUNT_JSON to the service-account "
             "JSON file (see ANLEITUNG.md)")


def connect():
    """The API client, signed in as the service account."""
    from google.oauth2 import service_account
    from googleapiclient.discovery import build

    creds = service_account.Credentials.from_service_account_file(
        credentials_path(), scopes=[SCOPE]
    )
    # The static document: the calls are the ones this file was checked
    # against, not whatever a later revision renames.
    return build("androidpublisher", "v3", credentials=creds,
                 static_discovery=True, cache_discovery=False)


def read(path: str) -> str:
    return open(path, encoding="utf-8").read().strip()


def local_listings() -> dict[str, dict]:
    """What tool/export_play_metadata.py laid out, per Play language."""
    if not os.path.isdir(METADATA):
        sys.exit(f"{METADATA} is missing — run tool/export_play_metadata.py first")
    listings = {}
    for folder in sorted(glob.glob(os.path.join(METADATA, "*"))):
        code = os.path.basename(folder)
        texts = {field: read(os.path.join(folder, f"{field}.txt")) for field in LIMITS}
        for field, limit in LIMITS.items():
            if not 0 < len(texts[field]) <= limit:
                sys.exit(f"{code} {field}: {len(texts[field])} characters, "
                         f"allowed 1 to {limit}")
        shots = sorted(
            glob.glob(os.path.join(folder, "images", "phoneScreenshots", "*.png")),
            key=lambda p: int(os.path.splitext(os.path.basename(p))[0]),
        )
        banner = os.path.join(folder, "images", "featureGraphic.png")
        if not 2 <= len(shots) <= 8 or not os.path.exists(banner):
            sys.exit(f"{code}: {len(shots)} screenshots (2 to 8 allowed), "
                     f"feature graphic {'there' if os.path.exists(banner) else 'missing'}")
        notes = read(os.path.join(folder, "changelogs", "default.txt"))
        if not 0 < len(notes) <= NOTES_LIMIT:
            sys.exit(f"{code} release notes: {len(notes)} characters, "
                     f"allowed 1 to {NOTES_LIMIT}")
        listings[code] = {"texts": texts, "shots": shots, "banner": banner,
                          "notes": notes}
    if not listings:
        sys.exit(f"{METADATA} holds no listing")
    return listings


def finish(edits, edit_id: str, commit: bool, *, not_sent_for_review: bool) -> None:
    """Validates the edit, and commits it or throws it away."""
    if commit:
        # A commit validates as well; validating first only gives the clearer
        # error if something is wrong.
        edits.validate(packageName=PACKAGE, editId=edit_id).execute()
        edits.commit(
            packageName=PACKAGE,
            editId=edit_id,
            changesNotSentForReview=not_sent_for_review,
        ).execute()
        log("committed.")
    else:
        edits.validate(packageName=PACKAGE, editId=edit_id).execute()
        edits.delete(packageName=PACKAGE, editId=edit_id).execute()
        log("checked by Google, nothing changed (run with --commit to publish).")


def cmd_listing(service, args) -> int:
    from googleapiclient.http import MediaFileUpload

    local = local_listings()
    edits = service.edits()
    edit_id = edits.insert(packageName=PACKAGE, body={}).execute()["id"]
    existing = {
        item["language"]
        for item in edits.listings()
        .list(packageName=PACKAGE, editId=edit_id)
        .execute()
        .get("listings", [])
    }
    log(f"the store has {len(existing)} listing languages; sending "
        f"{', '.join(local)}")

    for code, listing in local.items():
        if not args.images_only:
            body = {
                "language": code,
                "title": listing["texts"]["title"],
                "shortDescription": listing["texts"]["short_description"],
                "fullDescription": listing["texts"]["full_description"],
            }
            # patch keeps what is not sent (the promo video); a language the
            # store does not have yet has nothing to patch and is created.
            call = edits.listings().patch if code in existing else edits.listings().update
            call(packageName=PACKAGE, editId=edit_id, language=code, body=body).execute()
            log(f"  {code}: texts {'updated' if code in existing else 'created'}")
        if not args.texts_only:
            extra = {}
            if args.ai_state:
                extra["aiGeneratedState"] = AI_STATES[args.ai_state]
            for image_type, files in (
                ("phoneScreenshots", listing["shots"]),
                ("featureGraphic", [listing["banner"]]),
            ):
                edits.images().deleteall(
                    packageName=PACKAGE, editId=edit_id, language=code,
                    imageType=image_type,
                ).execute()
                for path in files:
                    edits.images().upload(
                        packageName=PACKAGE, editId=edit_id, language=code,
                        imageType=image_type,
                        media_body=MediaFileUpload(path, mimetype="image/png"),
                        **extra,
                    ).execute()
                log(f"  {code}: {len(files)} × {image_type}")

    if args.clear_other_images:
        others = sorted(existing - set(local))
        for code in others:
            for image_type in ("phoneScreenshots", "featureGraphic"):
                edits.images().deleteall(
                    packageName=PACKAGE, editId=edit_id, language=code,
                    imageType=image_type,
                ).execute()
        log(f"  images removed from {len(others)} other languages: "
            f"{', '.join(others) or 'none'}")

    finish(edits, edit_id, args.commit, not_sent_for_review=args.not_sent_for_review)
    return 0


def pubspec_version() -> tuple[str, int]:
    match = re.search(r"^version:\s*([0-9.]+)\+(\d+)", read("pubspec.yaml"), re.M)
    return match.group(1), int(match.group(2))


def cmd_release(service, args) -> int:
    from googleapiclient.http import MediaFileUpload

    if not os.path.exists(args.bundle):
        sys.exit(f"{args.bundle} does not exist")
    if args.status == "inProgress" and not 0 < args.fraction < 1:
        sys.exit("--fraction must be above 0 and below 1 for a staged rollout")
    name, code = pubspec_version()
    local = local_listings()
    edits = service.edits()
    edit_id = edits.insert(packageName=PACKAGE, body={}).execute()["id"]

    uploaded = edits.bundles().upload(
        packageName=PACKAGE,
        editId=edit_id,
        media_body=MediaFileUpload(
            args.bundle, mimetype="application/octet-stream", resumable=True
        ),
    ).execute()
    got = int(uploaded["versionCode"])
    if got != code:
        edits.delete(packageName=PACKAGE, editId=edit_id).execute()
        sys.exit(f"the bundle is version code {got}, pubspec.yaml says {code} — "
                 "this is not the build of this commit")
    log(f"bundle uploaded: {name} ({got})")

    release = {
        "name": name,
        "versionCodes": [str(got)],
        "status": args.status,
        "releaseNotes": [
            {"language": language, "text": listing["notes"]}
            for language, listing in local.items()
        ],
    }
    if args.status == "inProgress":
        release["userFraction"] = args.fraction
    edits.tracks().update(
        packageName=PACKAGE,
        editId=edit_id,
        track=args.track,
        body={"track": args.track, "releases": [release]},
    ).execute()
    log(f"track {args.track}: release {name} as {args.status}"
        + (f" at {args.fraction:.0%}" if args.status == "inProgress" else "")
        + f", notes in {', '.join(local)}")

    finish(edits, edit_id, args.commit, not_sent_for_review=args.not_sent_for_review)
    return 0


def cmd_reviews(service, args) -> int:
    """The reviews Google hands out: those written or changed in the last
    week. Printed without the reviewer's name."""
    response = service.reviews().list(packageName=PACKAGE, maxResults=100).execute()
    reviews = response.get("reviews", [])
    log(f"{len(reviews)} reviews from the last week")
    for review in reviews:
        for comment in review.get("comments", []):
            user = comment.get("userComment")
            if not user:
                continue
            seconds = int(user.get("lastModified", {}).get("seconds", 0))
            log(json.dumps({
                "stars": user.get("starRating"),
                "language": user.get("reviewerLanguage"),
                "app_version": user.get("appVersionName"),
                "modified_unix": seconds,
                "text": user.get("text", "").strip(),
            }, ensure_ascii=False))
    return 0


def selftest() -> int:
    """Replays `listing` and `release` against the API's own description,
    with canned answers instead of the network. Proves that every call exists
    under that name, takes those parameters and builds a URL — which is all
    that can be proved without a key."""
    import tempfile

    from googleapiclient.discovery import build
    from googleapiclient.http import HttpMockSequence

    seen: list[str] = []

    class Recording(HttpMockSequence):
        def request(self, uri, method="GET", body=None, headers=None, **kw):
            seen.append(f"{method} {uri.split('/androidpublisher/v3/')[-1].split('?')[0]}")
            return super().request(uri, method=method, body=body, headers=headers, **kw)

    def service(answers):
        # A mock transport needs no credentials at all. An answer is a JSON
        # body, or (extra headers, JSON body).
        replies = []
        for answer in answers:
            headers, body = answer if isinstance(answer, tuple) else ({}, answer)
            replies.append(({"status": "200", **headers}, json.dumps(body)))
        http = Recording(replies)
        return build("androidpublisher", "v3", http=http, static_discovery=True,
                     cache_discovery=False)

    global METADATA
    with tempfile.TemporaryDirectory() as tmp:
        METADATA = os.path.join(tmp, "android")
        png = (b"\x89PNG\r\n\x1a\n" + b"\0" * 32)
        for code in ("en-US", "xx-NEW"):
            base = os.path.join(METADATA, code)
            os.makedirs(os.path.join(base, "images", "phoneScreenshots"))
            os.makedirs(os.path.join(base, "changelogs"))
            for field in LIMITS:
                open(os.path.join(base, f"{field}.txt"), "w").write("text")
            for i in (1, 2):
                open(os.path.join(base, "images", "phoneScreenshots", f"{i}.png"),
                     "wb").write(png)
            open(os.path.join(base, "images", "featureGraphic.png"), "wb").write(png)
            open(os.path.join(base, "changelogs", "default.txt"), "w").write("notes")
        bundle = os.path.join(tmp, "app.aab")
        open(bundle, "wb").write(b"aab")

        parser = arguments()
        # listing: en-US exists (patch), xx-NEW does not (update); fr-FR is
        # in the store but not sent, and loses its two kinds of images.
        per_language = [{}, {}, {}, {}, {}, {}]  # texts, deleteall+2, deleteall+1
        store = {"listings": [{"language": "en-US"}, {"language": "fr-FR"}]}
        answers = [{"id": "e1"}, store] + per_language * 2 + [{}, {}] + [{}, {}]
        cmd_listing(service(answers),
                    parser.parse_args(["listing", "--clear-other-images"]))
        expected = (
            ["POST applications/com.thinkube.qubble/edits",
             "GET applications/com.thinkube.qubble/edits/e1/listings"]
            + [f"{verb} applications/com.thinkube.qubble/edits/e1/listings/{code}{tail}"
               for code, texts in (("en-US", "PATCH"), ("xx-NEW", "PUT"))
               for verb, tail in ((texts, ""), ("DELETE", "/phoneScreenshots"),
                                  ("POST", "/phoneScreenshots"),
                                  ("POST", "/phoneScreenshots"),
                                  ("DELETE", "/featureGraphic"),
                                  ("POST", "/featureGraphic"))]
            + ["DELETE applications/com.thinkube.qubble/edits/e1/listings/fr-FR/phoneScreenshots",
               "DELETE applications/com.thinkube.qubble/edits/e1/listings/fr-FR/featureGraphic",
               "POST applications/com.thinkube.qubble/edits/e1:validate",
               "DELETE applications/com.thinkube.qubble/edits/e1"]
        )
        if seen != expected:
            log("listing sent:\n  " + "\n  ".join(seen))
            log("expected:\n  " + "\n  ".join(expected))
            return 1

        seen.clear()
        _, code = pubspec_version()
        # The bundle goes up resumably: one call opens the upload and is
        # answered with where to send the bytes, the next one sends them.
        session = ("https://androidpublisher.googleapis.com/upload/androidpublisher"
                   "/v3/applications/com.thinkube.qubble/edits/e2/bundles"
                   "?upload_id=selftest")
        answers = [{"id": "e2"}, ({"location": session}, {}),
                   {"versionCode": code}, {}, {}, {}]
        cmd_release(service(answers),
                    parser.parse_args(["release", bundle, "--commit"]))
        expected = [
            "POST applications/com.thinkube.qubble/edits",
            "POST applications/com.thinkube.qubble/edits/e2/bundles",
            "PUT applications/com.thinkube.qubble/edits/e2/bundles",
            "PUT applications/com.thinkube.qubble/edits/e2/tracks/production",
            "POST applications/com.thinkube.qubble/edits/e2:validate",
            "POST applications/com.thinkube.qubble/edits/e2:commit",
        ]
        if seen != expected:
            log("release sent:\n  " + "\n  ".join(seen))
            log("expected:\n  " + "\n  ".join(expected))
            return 1
    log("selftest passed: every call exists and builds, in the expected order.")
    return 0


def arguments() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)

    def publishing(p):
        p.add_argument("--commit", action="store_true",
                       help="publish; without it the edit is only checked")
        p.add_argument("--not-sent-for-review", action="store_true",
                       help="hold the changes in the Console until they are "
                            "sent for review there")

    listing = sub.add_parser("listing", help="texts and images of the listings")
    publishing(listing)
    only = listing.add_mutually_exclusive_group()
    only.add_argument("--texts-only", action="store_true")
    only.add_argument("--images-only", action="store_true")
    listing.add_argument("--clear-other-images", action="store_true",
                         help="remove screenshots and feature graphic from "
                              "every language not sent, so they fall back to "
                              "the default language's")
    listing.add_argument("--ai-state", choices=sorted(AI_STATES),
                         help="Google's AI attestation for the images; the "
                              "account holder decides, default is to send none")

    release = sub.add_parser("release", help="an app bundle onto a track")
    publishing(release)
    release.add_argument("bundle")
    release.add_argument("--track", default="production")
    release.add_argument("--status", choices=STATUSES, default="draft")
    release.add_argument("--fraction", type=float, default=0.2,
                         help="share of users for --status inProgress")

    sub.add_parser("reviews", help="the last week's reviews, without names")
    sub.add_parser("selftest", help="replay the calls offline")
    return parser


def main() -> int:
    args = arguments().parse_args()
    if args.command == "selftest":
        return selftest()
    service = connect()
    return {"listing": cmd_listing, "release": cmd_release,
            "reviews": cmd_reviews}[args.command](service, args)


if __name__ == "__main__":
    raise SystemExit(main())
